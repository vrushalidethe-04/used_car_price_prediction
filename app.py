import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="AutoPrice AI",
    page_icon="🚗",
    layout="wide"
)

# Load trained model and preprocessor
model = joblib.load("backend/model/car_price_model.pkl")
preprocessor = joblib.load("backend/model/preprocessor.pkl")

st.title("🚗 AutoPrice AI")
st.subheader("Used Car Price Prediction")

st.write(
    "Enter the details of your used car to estimate its selling price "
    "using Machine Learning."
)

st.divider()

col1, col2 = st.columns(2)

with col1:
    car_age = st.number_input(
        "Car Age (years)",
        min_value=0,
        max_value=30,
        value=5
    )

    kilometers = st.number_input(
        "Kilometers Driven",
        min_value=0,
        value=50000
    )

    engine = st.number_input(
        "Engine Capacity (cc)",
        min_value=500,
        max_value=5000,
        value=1200
    )

    mileage = st.number_input(
        "Mileage (km/l)",
        min_value=1.0,
        max_value=50.0,
        value=18.5,
        step=0.1
    )

with col2:
    owners = st.selectbox(
        "Previous Owners",
        [1, 2, 3]
    )

    fuel = st.selectbox(
        "Fuel Type",
        ["Petrol", "Diesel", "CNG"]
    )

    transmission = st.selectbox(
        "Transmission",
        ["Manual", "Automatic"]
    )

    brand = st.selectbox(
        "Car Brand",
        [
            "Maruti",
            "Hyundai",
            "Tata",
            "Honda",
            "Toyota",
            "Mahindra",
            "Kia",
            "Renault"
        ]
    )

st.divider()

if st.button("🔍 Predict Selling Price"):

    input_data = pd.DataFrame([{
        "Car_Age": car_age,
        "Kilometers_Driven": kilometers,
        "Engine_Capacity": engine,
        "Mileage": mileage,
        "Previous_Owners": owners,
        "Fuel_Type": fuel,
        "Transmission": transmission,
        "Car_Brand": brand
    }])

    processed_data = preprocessor.transform(input_data)

    prediction = model.predict(processed_data)[0]

    st.success("Prediction generated successfully!")

    st.metric(
        "Estimated Selling Price",
        f"₹ {prediction:,.2f}"
    )

    st.info(
        "This is an estimated price generated by the trained Machine Learning model."
    )

st.divider()

st.subheader("📊 Model Information")

st.write("Model: Linear Regression")
st.write("Dataset: 500 used-car records")
st.write("Evaluation: MAE, MSE, RMSE and R²")
st.write("R² Score: 0.9786")